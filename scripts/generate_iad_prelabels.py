def _entry_from_value(value: Any, base_dir: Path) -> dict[str, str]:
    if isinstance(value, str):
        raw_path = value
        raw_name = None
    elif isinstance(value, dict):
        raw_path = next(
            (value[key] for key in _PATH_KEYS if value.get(key)),
            None,
        )
        raw_name = next(
            (value[key] for key in _NAME_KEYS if value.get(key)),
            None,
        )
        if raw_path is None:
            raise ValueError(
                f"Manifest entry has no supported path key {_PATH_KEYS}: {value}"
            )
    else:
        raise TypeError(f"Unsupported manifest entry: {value!r}")

    path = Path(str(raw_path))
    if not path.is_absolute():
        path = base_dir / path
    path = path.resolve()
    default_name = path.stem.removesuffix("_Train_Test")
    return {"name": str(raw_name or default_name), "path": str(path)}


def load_manifest_entries(path: Path) -> list[dict[str, str]]:
    suffix = path.suffix.lower()
    if suffix == ".csv":
        with path.open("r", encoding="utf-8-sig", newline="") as handle:
            values: Any = list(csv.DictReader(handle))
    elif suffix == ".jsonl":
        with path.open("r", encoding="utf-8") as handle:
            values = [json.loads(line) for line in handle if line.strip()]
    else:
        with path.open("r", encoding="utf-8") as handle:
            values = json.load(handle)
        if isinstance(values, dict):
            for key in ("datasets", "items", "files"):
                if key in values:
                    values = values[key]
                    break
            else:
                values = [values]
    if not isinstance(values, list):
        raise ValueError("Manifest must resolve to a list of dataset entries")
    return [_entry_from_value(value, path.parent) for value in values]


def resolve_dataset_entries(
    dataset_pkls: Sequence[str],
    manifest: Path | None,
) -> list[dict[str, str]]:
    entries = [
        _entry_from_value(value, Path.cwd())
        for value in dataset_pkls
    ]
    if manifest is not None:
        entries.extend(load_manifest_entries(manifest.resolve()))
    if not entries:
        raise ValueError("Provide at least one --dataset-pkl or --manifest")
    seen_paths: set[str] = set()
    unique_entries = []
    for entry in entries:
        if entry["path"] in seen_paths:
            continue
        seen_paths.add(entry["path"])
        unique_entries.append(entry)
    return unique_entries


def load_iad_pickle(path: Path) -> dict[str, np.ndarray]:
    """Load an IAD source through the data layer's restricted unpickler."""

    from dataio.iad.pickle_io import safe_load_iad_pickle

    bundle = safe_load_iad_pickle(path)
    return {
        "train_data": bundle.train_data.detach().cpu().numpy(),
        "train_label": bundle.train_labels,
        "test_data": bundle.test_data.detach().cpu().numpy(),
        "test_label": bundle.test_labels,
    }


def _safe_directory_name(name: str) -> str:
    value = re.sub(r"[^A-Za-z0-9_.-]+", "_", name.strip())
    return value.strip("._") or "dataset"


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _canonical_json_sha256(value: Any) -> str:
    encoded = json.dumps(
        value,
        sort_keys=True,
        separators=(",", ":"),
        allow_nan=False,
    ).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


def load_strict_pilot_manifest(path: Path) -> list[Any]:
    """Load the canonical eight-field pilot JSONL without schema drift."""

    from dataio.iad.manifest import IADManifestRecord, MANIFEST_FIELDS

    source = path.expanduser().resolve()
    if source.suffix.lower() != ".jsonl":
        raise ValueError("--pilot-manifest must be the canonical JSONL file")
    if tuple(MANIFEST_FIELDS) != PILOT_MANIFEST_FIELDS:
        raise RuntimeError(
            "The IAD data-layer manifest contract differs from this CLI"
        )
    if not source.is_file():
        raise FileNotFoundError(source)

    records: list[Any] = []
    with source.open("r", encoding="utf-8") as handle:
        for line_number, line in enumerate(handle, start=1):
            if not line.strip():
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(
                    f"{source}:{line_number}: invalid JSON: {exc}"
                ) from exc
            if not isinstance(row, dict):
                raise ValueError(
                    f"{source}:{line_number}: row must be a JSON object"
                )
            if tuple(row) != PILOT_MANIFEST_FIELDS:
                raise ValueError(
                    f"{source}:{line_number}: fields must be exactly, and in "
                    f"order, {list(PILOT_MANIFEST_FIELDS)}"
                )
            for field_name in (
                "sample_id",
                "hash",
                "modulation",
                "split",
                "source_path",
            ):
                if not isinstance(row[field_name], str):
                    raise ValueError(
                        f"{source}:{line_number}: {field_name} must be a string"
                    )
            for field_name in ("source_index", "label"):
                if type(row[field_name]) is not int:
                    raise ValueError(
                        f"{source}:{line_number}: {field_name} must be an integer"
                    )
            if not isinstance(row["shape"], list) or not row["shape"]:
                raise ValueError(
                    f"{source}:{line_number}: shape must be a non-empty array"
                )
            if any(type(size) is not int for size in row["shape"]):
                raise ValueError(
                    f"{source}:{line_number}: shape entries must be integers"
                )
            if row["modulation"] != row["modulation"].strip().upper():
                raise ValueError(
                    f"{source}:{line_number}: modulation must be canonical uppercase"
                )
            if row["split"] != "test" or row["label"] != 1:
                raise ValueError(
                    f"{source}:{line_number}: pilot rows must be split='test', "
                    "label=1"
                )
            if not Path(row["source_path"]).is_absolute():
                raise ValueError(
                    f"{source}:{line_number}: source_path must be absolute"
                )
            records.append(IADManifestRecord.from_mapping(row))

    if not records:
        raise ValueError(f"Pilot manifest contains no records: {source}")
    sample_ids = [record.sample_id for record in records]
    content_hashes = [record.hash for record in records]
    if len(set(sample_ids)) != len(sample_ids):
        raise ValueError("Pilot manifest contains duplicate sample_id values")
    if len(set(content_hashes)) != len(content_hashes):
        raise ValueError(
            "Pilot manifest must be globally content-hash unique"
        )
    return records


def _normal_hash_group_split(
    train_data: Any,
    *,
    modulation: str,
    heldout_fraction: float,
    seed: int,
) -> tuple[np.ndarray, np.ndarray, dict[str, Any]]:
    """Split normal train data into disjoint content-hash groups."""

    from dataio.iad.manifest import hash_iad_sample

    if not 0.0 < heldout_fraction < 1.0:
        raise ValueError("--normal-calibration-fraction must be in (0, 1)")
    hash_to_indices: dict[str, list[int]] = {}
    for source_index in range(int(train_data.shape[0])):
        _, content_hash = hash_iad_sample(train_data[source_index])
        hash_to_indices.setdefault(content_hash, []).append(source_index)
    if len(hash_to_indices) < 2:
        raise ValueError(
            f"{modulation}: need at least two unique normal-train hash groups "
            "for a disjoint fit/QC split"
        )

    def split_order(content_hash: str) -> tuple[str, str]:
        payload = (
            f"IAD_NORMAL_SPLIT_V1\0{seed}\0{modulation}\0{content_hash}"
        ).encode("utf-8")
        return hashlib.sha256(payload).hexdigest(), content_hash

    ordered_hashes = sorted(hash_to_indices, key=split_order)
    heldout_group_count = int(round(heldout_fraction * len(ordered_hashes)))
    heldout_group_count = min(
        max(heldout_group_count, 1),
        len(ordered_hashes) - 1,
    )
    heldout_hashes = set(ordered_hashes[:heldout_group_count])
    fit_hashes = set(ordered_hashes[heldout_group_count:])
    fit_indices = np.asarray(
        sorted(
            index
            for content_hash in fit_hashes
            for index in hash_to_indices[content_hash]
        ),
        dtype=np.int64,
    )
    heldout_indices = np.asarray(
        sorted(
            index
            for content_hash in heldout_hashes
            for index in hash_to_indices[content_hash]
        ),
        dtype=np.int64,
    )
    overlap = fit_hashes.intersection(heldout_hashes)
    if overlap:
        raise AssertionError("Normal split contains overlapping hash groups")
    metadata = {
        "algorithm": "IAD_NORMAL_SPLIT_V1",
        "seed": int(seed),
        "requested_heldout_fraction": float(heldout_fraction),
        "normal_sample_count": int(train_data.shape[0]),
        "unique_hash_group_count": int(len(ordered_hashes)),
        "background_fit_group_count": int(len(fit_hashes)),
        "heldout_normal_group_count": int(len(heldout_hashes)),
        "background_fit_available_sample_count": int(fit_indices.size),
        "heldout_normal_sample_count": int(heldout_indices.size),
        "hash_group_overlap_count": 0,
        "background_fit_hash_set_digest": (
            "sha256:" + _canonical_json_sha256(sorted(fit_hashes))
        ),
        "heldout_hash_set_digest": (
            "sha256:" + _canonical_json_sha256(sorted(heldout_hashes))
        ),
    }
    return fit_indices, heldout_indices, metadata


def _prepare_normal_threshold_cache(
    prelabeler: RobustCFARPrelabeler,
    train_data: Any,
    heldout_indices: np.ndarray,
) -> list[tuple[np.ndarray, np.ndarray]]:
    """Compute score/local-threshold arrays once for all threshold trials."""

    return [
        prelabeler.prepare_threshold_cache(train_data[int(source_index)])
        for source_index in heldout_indices
    ]


def _select_normal_only_threshold(
    base_config: PrelabelConfig,
    prelabeler: RobustCFARPrelabeler,
    prepared_normal: Sequence[tuple[np.ndarray, np.ndarray]],
    *,
    target_rate: float,
    search_min: float,
    search_max: float | None,
    search_step: float,
    strong_margin: float | None,
) -> tuple[PrelabelConfig, dict[str, Any]]:
    """Select the most sensitive grid threshold meeting normal-only QC."""

    if not 0.0 < target_rate < 1.0:
        raise ValueError("--target-normal-proposal-rate must be in (0, 1)")
    if not prepared_normal:
        raise ValueError("Cannot select a threshold without held-out normals")
    if search_min < 0:
        raise ValueError("--threshold-search-min cannot be negative")
    if search_step <= 0:
        raise ValueError("--threshold-search-step must be positive")
    resolved_max = (
        base_config.score_clip + search_step
        if search_max is None
        else float(search_max)
    )
    if resolved_max < search_min:
        raise ValueError(
            "--threshold-search-max must be >= --threshold-search-min"
        )
    resolved_margin = (
        base_config.strong_score_threshold
        - base_config.global_score_threshold
        if strong_margin is None
        else float(strong_margin)
    )
    if resolved_margin < 0:
        raise ValueError("--strong-threshold-margin cannot be negative")

    span = resolved_max - search_min
    regular_trial_count = int(np.floor(span / search_step + 1e-12)) + 1
    thresholds = [
        float(round(search_min + index * search_step, 12))
        for index in range(regular_trial_count)
    ]
    if thresholds[-1] < resolved_max - 1e-12:
        thresholds.append(float(resolved_max))

    trials: list[dict[str, Any]] = []
    selected_global: float | None = None
    selected_strong: float | None = None
    selected_rate: float | None = None
    selected_nonempty_count: int | None = None
    heldout_count = len(prepared_normal)
    for global_threshold in thresholds:
        strong_threshold = float(global_threshold + resolved_margin)
        nonempty_count = 0
        for score_map, local_threshold in prepared_normal:
            proposal = prelabeler.proposal_from_threshold_cache(
                score_map,
                local_threshold,
                global_score_threshold=global_threshold,
                strong_score_threshold=strong_threshold,
            )
            nonempty_count += int(bool(proposal.any()))
        achieved_rate = float(nonempty_count / heldout_count)
        trials.append(
            {
                "global_score_threshold": global_threshold,
                "strong_score_threshold": strong_threshold,
                "heldout_normal_sample_count": heldout_count,
                "proposal_nonempty_count": int(nonempty_count),
                "proposal_nonempty_rate": achieved_rate,
                "meets_target": bool(achieved_rate <= target_rate),
            }
        )
        if achieved_rate <= target_rate:
            selected_global = global_threshold
            selected_strong = strong_threshold
            selected_rate = achieved_rate
            selected_nonempty_count = nonempty_count
            break

    if selected_global is None or selected_strong is None:
        raise ValueError(
            "No threshold in the configured search grid satisfies the "
            "target normal proposal rate"
        )
    selected_config = replace(
        base_config,
        global_score_threshold=selected_global,
        strong_score_threshold=selected_strong,
    )
    selection = {
        "mode": "heldout_normal_target_rate_grid_search",
        "selection_population": "heldout_normal_train_hash_groups_only",
        "selection_rule": (
            "lowest ascending-grid global threshold with nonempty proposal "
            "rate <= target; strong threshold = global + margin"
        ),
        "target_normal_proposal_rate": float(target_rate),
        "search": {
            "global_threshold_min": float(search_min),
            "global_threshold_max": float(resolved_max),
            "global_threshold_step": float(search_step),
            "strong_threshold_link": "global_plus_margin",
            "strong_threshold_margin": float(resolved_margin),
            "score_cache_reused": True,
            "local_threshold_cache_reused": True,
        },
        "trials": trials,
        "selected_global_score_threshold": float(selected_global),
        "selected_strong_score_threshold": float(selected_strong),
        "achieved_normal_proposal_nonempty_count": int(
            selected_nonempty_count
        ),
        "achieved_normal_proposal_rate": float(selected_rate),
        "heldout_normal_sample_count": int(heldout_count),
        "anomaly_samples_used": 0,
    }
    return selected_config, selection


def _fixed_normal_qc(
    prelabeler: RobustCFARPrelabeler,
    prepared_normal: Sequence[tuple[np.ndarray, np.ndarray]],
    *,
    threshold_selection: dict[str, Any],
) -> dict[str, Any]:
    """Evaluate final fixed parameters on cached held-out normal scores."""

    histogram_bin_count = 4096
    score_histogram = np.zeros(histogram_bin_count, dtype=np.int64)
    sample_max_scores: list[float] = []
    nonempty_count = 0
    proposal_pixel_count = 0
    total_pixel_count = 0
    for score_map, local_threshold in prepared_normal:
        score = np.asarray(score_map, dtype=np.float32)
        proposal = prelabeler.proposal_from_threshold_cache(
            score,
            local_threshold,
        )
        score_histogram += np.histogram(
            score,
            bins=histogram_bin_count,
            range=(0.0, prelabeler.config.score_clip),
        )[0]
        proposal_pixels = int(proposal.sum())
        nonempty_count += int(proposal_pixels > 0)
        proposal_pixel_count += proposal_pixels
        total_pixel_count += int(proposal.size)
        sample_max_scores.append(float(score.max()))

    if total_pixel_count == 0:
        raise ValueError("Held-out normal QC split is empty")

    cumulative = np.cumsum(score_histogram)
    histogram_total = int(cumulative[-1])

    def histogram_quantile(probability: float) -> float:
        target = max(1, int(np.ceil(probability * histogram_total)))
        bin_index = int(np.searchsorted(cumulative, target, side="left"))
        return float(
            min(
                prelabeler.config.score_clip,
                (bin_index + 1)
                * prelabeler.config.score_clip
                / histogram_bin_count,
            )
        )

    score_quantiles = {
        f"p{int(probability * 1000):03d}": histogram_quantile(probability)
        for probability in (0.5, 0.9, 0.95, 0.99, 0.999)
    }
    sample_max_array = np.asarray(sample_max_scores, dtype=np.float64)
    sample_max_quantiles = {
        f"p{int(probability * 1000):03d}": float(
            np.quantile(sample_max_array, probability)
        )
        for probability in (0.5, 0.9, 0.95, 0.99)
    }
    return {
        "evaluation_population": "heldout_normal_train_hash_groups_only",
        "heldout_normal_sample_count": int(len(prepared_normal)),
        "proposal_nonempty_count": int(nonempty_count),
        "proposal_nonempty_rate": float(
            nonempty_count / len(prepared_normal)
        ),
        "proposal_pixel_count": int(proposal_pixel_count),
        "evaluated_pixel_count": int(total_pixel_count),
        "proposal_pixel_rate": float(
            proposal_pixel_count / total_pixel_count
        ),
        "score_map_quantiles": score_quantiles,
        "score_map_quantile_method": (
            f"{histogram_bin_count}-bin histogram over "
            f"[0,{prelabeler.config.score_clip}]"
        ),
        "sample_max_score_quantiles": sample_max_quantiles,
        "threshold_tuning": {
            "mode": threshold_selection["mode"],
            "target_normal_proposal_rate": threshold_selection[
                "target_normal_proposal_rate"
            ],
            "selected_global_score_threshold": prelabeler.config.global_score_threshold,
            "selected_strong_score_threshold": prelabeler.config.strong_score_threshold,
            "anomaly_samples_used": threshold_selection[
                "anomaly_samples_used"
            ],
        },
    }


def _select_pilot_indices(
    test_labels: np.ndarray,
    *,
    normal_label: float,
    pilot_label: str,
    pilot_count: int,
    seed: int,
) -> np.ndarray:
    labels = np.asarray(test_labels).reshape(-1)
    if pilot_label == "anomaly":
        eligible = np.flatnonzero(labels != normal_label)
    elif pilot_label == "normal":
        eligible = np.flatnonzero(labels == normal_label)
    else:
        eligible = np.arange(labels.shape[0], dtype=np.int64)
    if eligible.size == 0:
        raise ValueError(f"No test samples match pilot_label={pilot_label!r}")
    if pilot_count <= 0 or pilot_count >= eligible.size:
        return eligible.astype(np.int64, copy=False)
    rng = np.random.default_rng(seed)
    return np.sort(
        rng.choice(eligible, size=pilot_count, replace=False)
    ).astype(np.int64)


def config_from_args(args: argparse.Namespace) -> PrelabelConfig:
    return PrelabelConfig(
        log_epsilon=args.log_epsilon,
        mad_consistency_scale=args.mad_consistency_scale,
        mad_floor=args.mad_floor,
        score_mode=args.score_mode,
        score_clip=args.score_clip,
        gaussian_sigma=args.gaussian_sigma,
        global_score_threshold=args.global_score_threshold,
        local_window_size=args.local_window_size,
        local_threshold_scale=args.local_threshold_scale,
        local_mad_floor=args.local_mad_floor,
        strong_score_threshold=args.strong_score_threshold,
        closing_iterations=args.closing_iterations,
        fill_holes=args.fill_holes,
        min_component_area=args.min_component_area,
        min_ridge_length=args.min_ridge_length,
        min_ridge_linearity=args.min_ridge_linearity,
        connectivity=args.connectivity,
        bbox_padding=args.bbox_padding,
    )


def process_pilot_manifest(
    pilot_manifest_path: Path,
    *,
    output_root: Path,
    config: PrelabelConfig,
    normal_calibration_fraction: float,
    normal_split_seed: int,
    fit_max_samples: int | None,
    target_normal_proposal_rate: float | None,
    threshold_search_min: float,
    threshold_search_max: float | None,
    threshold_search_step: float,
    strong_threshold_margin: float | None,
) -> dict[str, Any]:
    """Generate artifacts for exactly the canonical pilot-manifest rows."""

    from dataio.iad.manifest import hash_iad_sample
    from dataio.iad.pickle_io import safe_load_iad_pickle

    pilot_path = pilot_manifest_path.expanduser().resolve()
    pilot_hash_before = _sha256(pilot_path)
    records = load_strict_pilot_manifest(pilot_path)
    output_root.mkdir(parents=True, exist_ok=True)
    sample_dir = output_root / "samples"
    calibration_dir = output_root / "calibrations"
    sample_dir.mkdir(parents=True, exist_ok=True)
    calibration_dir.mkdir(parents=True, exist_ok=True)

    records_by_source: dict[Path, list[Any]] = {}
    for record in records:
        source_path = Path(record.source_path).expanduser().resolve()
        records_by_source.setdefault(source_path, []).append(record)

    rows_by_sample_id: dict[str, dict[str, Any]] = {}
    source_summaries: list[dict[str, Any]] = []
    for source_path in sorted(records_by_source, key=lambda value: str(value).casefold()):
        source_records = records_by_source[source_path]
        modulations = {record.modulation for record in source_records}
        if len(modulations) != 1:
            raise ValueError(
                f"{source_path}: pilot rows disagree on modulation: "
                f"{sorted(modulations)}"
            )
        modulation = next(iter(modulations))
        source_hash_before = _sha256(source_path)
        bundle = safe_load_iad_pickle(source_path, modulation=modulation)

        available_fit_indices, heldout_indices, split_metadata = (
            _normal_hash_group_split(
                bundle.train_data,
                modulation=modulation,
                heldout_fraction=normal_calibration_fraction,
                seed=normal_split_seed,
            )
        )
        fit_indices = available_fit_indices
        if fit_max_samples is not None:
            if fit_max_samples < 1:
                raise ValueError("--fit-max-samples must be positive")
            if fit_max_samples < fit_indices.size:
                subset_seed_material = (
                    f"IAD_NORMAL_FIT_SUBSET_V1\0{normal_split_seed}\0"
                    f"{modulation}\0"
                    f"{split_metadata['background_fit_hash_set_digest']}"
                ).encode("utf-8")
                subset_seed = int.from_bytes(
                    hashlib.sha256(subset_seed_material).digest()[:8],
                    "big",
                )
                rng = np.random.default_rng(subset_seed)
                fit_indices = np.sort(
                    rng.choice(
                        fit_indices,
                        size=fit_max_samples,
                        replace=False,
                    )
                ).astype(np.int64)

        prelabeler = RobustCFARPrelabeler(config).fit(
            bundle.train_data[fit_indices.tolist()]
        )
        split_metadata["background_fit_used_sample_count"] = int(
            fit_indices.size
        )
        split_metadata["fit_max_samples"] = (
            None if fit_max_samples is None else int(fit_max_samples)
        )
        split_metadata["background_fit_indices_digest"] = (
            "sha256:"
            + hashlib.sha256(
                np.asarray(fit_indices, dtype="<i8").tobytes()
            ).hexdigest()
        )
        split_metadata["heldout_indices_digest"] = (
            "sha256:"
            + hashlib.sha256(
                np.asarray(heldout_indices, dtype="<i8").tobytes()
            ).hexdigest()
        )

        prepared_normal = _prepare_normal_threshold_cache(
            prelabeler,
            bundle.train_data,
            heldout_indices,
        )
        if target_normal_proposal_rate is None:
            selected_config = config
            threshold_provenance: dict[str, Any] = {
                "mode": "fixed_config_no_automatic_tuning",
                "parameters_fixed_from": (
                    "CLI/defaults_before_pilot_inference"
                ),
                "selection_population": (
                    "heldout_normal_train_hash_groups_only"
                ),
                "target_normal_proposal_rate": None,
                "trials": [],
                "selected_global_score_threshold": float(
                    config.global_score_threshold
                ),
                "selected_strong_score_threshold": float(
                    config.strong_score_threshold
                ),
                "heldout_normal_sample_count": int(len(prepared_normal)),
                "anomaly_samples_used": 0,
            }
        else:
            selected_config, threshold_provenance = (
                _select_normal_only_threshold(
                    config,
                    prelabeler,
                    prepared_normal,
                    target_rate=target_normal_proposal_rate,
                    search_min=threshold_search_min,
                    search_max=threshold_search_max,
                    search_step=threshold_search_step,
                    strong_margin=strong_threshold_margin,
                )
            )
        # Only threshold fields differ, so the already fitted normal-only
        # background arrays remain valid under the per-source selected config.
        prelabeler.config = selected_config
        normal_qc = _fixed_normal_qc(
            prelabeler,
            prepared_normal,
            threshold_selection=threshold_provenance,
        )
        threshold_provenance["achieved_normal_proposal_nonempty_count"] = int(
            normal_qc["proposal_nonempty_count"]
        )
        threshold_provenance["achieved_normal_proposal_rate"] = float(
            normal_qc["proposal_nonempty_rate"]
        )
        if (
            target_normal_proposal_rate is not None
            and normal_qc["proposal_nonempty_rate"]
            > target_normal_proposal_rate
        ):
            raise AssertionError(
                "Selected threshold does not satisfy target normal proposal rate"
            )

        calibration_identity = {
            "method": "normal_train_log_median_mad_plus_robust_local_cfar",
            "source_sha256": source_hash_before,
            "modulation": modulation,
            "config": selected_config.to_dict(),
            "normal_split": split_metadata,
            "threshold_selection": threshold_provenance,
        }
        calibration_id = (
            "sha256:" + _canonical_json_sha256(calibration_identity)
        )
        calibration_stem = (
            f"{_safe_directory_name(modulation)}-"
            f"{source_hash_before[:12]}"
        )
        calibration_relative = (
            Path("calibrations") / f"{calibration_stem}.npz"
        )
        fit_indices_relative = (
            Path("calibrations")
            / f"{calibration_stem}.background_fit_indices.npy"
        )
        heldout_indices_relative = (
            Path("calibrations")
            / f"{calibration_stem}.heldout_normal_indices.npy"
        )
        normal_qc_relative = (
            Path("calibrations") / f"{calibration_stem}.normal_qc.json"
        )
        np.save(output_root / fit_indices_relative, fit_indices)
        np.save(output_root / heldout_indices_relative, heldout_indices)

        calibration_provenance: dict[str, Any] = {
            "calibration_id": calibration_id,
            "calibration_artifact": calibration_relative.as_posix(),
            "background_fit_indices_artifact": (
                fit_indices_relative.as_posix()
            ),
            "heldout_normal_indices_artifact": (
                heldout_indices_relative.as_posix()
            ),
            "normal_qc_artifact": normal_qc_relative.as_posix(),
            "source_path": str(source_path),
            "source_sha256": f"sha256:{source_hash_before}",
            "modulation": modulation,
            "config": selected_config.to_dict(),
            "normal_split": split_metadata,
            "threshold_selection": threshold_provenance,
            "normal_qc": normal_qc,
        }
        normal_qc_payload = {
            "calibration_id": calibration_id,
            "source_path": str(source_path),
            "modulation": modulation,
            "config": selected_config.to_dict(),
            "normal_split": split_metadata,
            "threshold_selection": threshold_provenance,
            "metrics": normal_qc,
        }
        with (output_root / normal_qc_relative).open(
            "w",
            encoding="utf-8",
        ) as handle:
            json.dump(
                normal_qc_payload,
                handle,
                indent=2,
                sort_keys=True,
                allow_nan=False,
            )
        prelabeler.save_calibration(
            output_root / calibration_relative,
            extra_metadata=calibration_provenance,
        )
        calibration_provenance["calibration_artifact_sha256"] = (
            "sha256:" + _sha256(output_root / calibration_relative)
        )

        for record in source_records:
            source_index = int(record.source_index)
            if source_index >= int(bundle.test_data.shape[0]):
                raise IndexError(
                    f"{record.sample_id}: source_index {source_index} is "
                    f"outside test_data length {bundle.test_data.shape[0]}"
                )
            if int(bundle.test_labels[source_index]) != record.label:
                raise ValueError(
                    f"{record.sample_id}: manifest label does not match source"
                )
            sample = bundle.test_data[source_index]
            actual_shape = tuple(int(size) for size in sample.shape)
            if actual_shape != record.shape:
                raise ValueError(
                    f"{record.sample_id}: manifest shape {record.shape} does "
                    f"not match source shape {actual_shape}"
                )
            actual_sample_id, actual_hash = hash_iad_sample(sample)
            if (
                actual_sample_id != record.sample_id
                or actual_hash != record.hash
            ):
                raise ValueError(
                    f"{record.sample_id}: source sample content hash does not "
                    "match the pilot manifest"
                )

            result = prelabeler.prelabel(sample)
            artifact_relative = Path("samples") / f"{record.sample_id}.npz"
            record_metadata = record.to_dict()
            result.save_npz(
                output_root / artifact_relative,
                extra_arrays={
                    "sample_id": np.asarray(record.sample_id),
                    "sample_hash": np.asarray(record.hash),
                    "source_index": np.asarray(
                        source_index,
                        dtype=np.int64,
                    ),
                    "label": np.asarray(record.label, dtype=np.int8),
                },
                extra_metadata={
                    **record_metadata,
                    "manifest_record": record_metadata,
                    "manifest_provenance": {
                        "path": str(pilot_path),
                        "sha256": f"sha256:{pilot_hash_before}",
                        "field_contract": list(PILOT_MANIFEST_FIELDS),
                    },
                    "source_content_verified": True,
                    "method": (
                        "normal_train_log_median_mad_plus_robust_local_cfar"
                    ),
                    "config": selected_config.to_dict(),
                    "calibration_provenance": calibration_provenance,
                },
            )
            artifact_path = output_root / artifact_relative
            row = {
                **record_metadata,
                "artifact": artifact_relative.as_posix(),
                "artifact_sha256": f"sha256:{_sha256(artifact_path)}",
                "score_map_key": "score_map",
                "proposal_mask_key": "proposal_mask",
                "binary_proposal_key": "binary_proposal",
                "bbox": result.bbox,
                "proposal_pixels": result.diagnostics["proposal_pixels"],
                "max_score": result.diagnostics["max_score"],
                "retained_component_count": result.diagnostics[
                    "retained_component_count"
                ],
                "calibration_id": calibration_id,
            }
            rows_by_sample_id[record.sample_id] = row

        source_hash_after = _sha256(source_path)
        if source_hash_after != source_hash_before:
            raise RuntimeError(
                f"Input PKL changed while processing: {source_path}"
            )
        source_summaries.append(
            {
                "source_path": str(source_path),
                "source_sha256_before": f"sha256:{source_hash_before}",
                "source_sha256_after": f"sha256:{source_hash_after}",
                "source_unchanged": True,
                "modulation": modulation,
                "pilot_sample_count": int(len(source_records)),
                "calibration_id": calibration_id,
                "calibration_artifact": calibration_relative.as_posix(),
                "selected_config": selected_config.to_dict(),
                "normal_split": split_metadata,
                "threshold_selection": threshold_provenance,
                "heldout_normal_qc": normal_qc,
            }
        )

    ordered_rows = [
        rows_by_sample_id[record.sample_id]
        for record in records
    ]
    prelabel_manifest_path = output_root / "prelabels.jsonl"
    with prelabel_manifest_path.open(
        "w",
        encoding="utf-8",
        newline="\n",
    ) as handle:
        for row in ordered_rows:
            handle.write(
                json.dumps(
                    row,
                    sort_keys=True,
                    allow_nan=False,
                )
                + "\n"
            )

    pilot_hash_after = _sha256(pilot_path)
    if pilot_hash_after != pilot_hash_before:
        raise RuntimeError(
            f"Pilot manifest changed while processing: {pilot_path}"
        )
    return {
        "mode": "canonical_pilot_manifest",
        "method": "normal_train_log_median_mad_plus_robust_local_cfar",
        "deep_model_used": False,
        "input_files_modified": False,
        "pilot_manifest": str(pilot_path),
        "pilot_manifest_sha256_before": f"sha256:{pilot_hash_before}",
        "pilot_manifest_sha256_after": f"sha256:{pilot_hash_after}",
        "pilot_manifest_unchanged": True,
        "pilot_manifest_field_contract": list(PILOT_MANIFEST_FIELDS),
        "pilot_sample_count": int(len(records)),
        "artifact_naming": "samples/<sample_id>.npz",
        "prelabel_manifest": str(prelabel_manifest_path),
        "config": config.to_dict(),
        "config_role": (
            "base_config_before_optional_per_source_normal_only_selection"
        ),
        "normal_calibration_fraction": float(
            normal_calibration_fraction
        ),
        "normal_split_seed": int(normal_split_seed),
        "threshold_selection": {
            "mode": (
                "fixed_config_no_automatic_tuning"
                if target_normal_proposal_rate is None
                else "per_source_heldout_normal_target_rate_grid_search"
            ),
            "normal_only_qc": True,
            "target_normal_proposal_rate": target_normal_proposal_rate,
            "anomaly_samples_used": 0,
        },
        "sources": source_summaries,
    }


def process_dataset(
    entry: dict[str, str],
    *,
    output_root: Path,
    config: PrelabelConfig,
    normal_label: float,
    pilot_label: str,
    pilot_count: int,
    pilot_seed: int,
    fit_max_samples: int | None,
) -> dict[str, Any]:
    pkl_path = Path(entry["path"])
    if not pkl_path.is_file():
        raise FileNotFoundError(pkl_path)
    input_hash_before = _sha256(pkl_path)
    dataset = load_iad_pickle(pkl_path)
    train_labels = np.asarray(dataset["train_label"]).reshape(-1)
    if train_labels.shape[0] != dataset["train_data"].shape[0]:
        raise ValueError(f"{pkl_path}: train data/label lengths differ")
    if not bool(np.all(train_labels == normal_label)):
        values = np.unique(train_labels).tolist()
        raise ValueError(
            f"{pkl_path}: fit is normal-only but train labels are {values}"
        )
    if dataset["test_data"].shape[0] != dataset["test_label"].reshape(-1).shape[0]:
        raise ValueError(f"{pkl_path}: test data/label lengths differ")

    fit_data = dataset["train_data"]
    fit_indices = np.arange(fit_data.shape[0], dtype=np.int64)
    if fit_max_samples is not None:
        if fit_max_samples < 1:
            raise ValueError("--fit-max-samples must be positive")
        if fit_max_samples < fit_data.shape[0]:
            rng = np.random.default_rng(pilot_seed + 1)
            fit_indices = np.sort(
                rng.choice(
                    fit_data.shape[0],
                    size=fit_max_samples,
                    replace=False,
                )
            ).astype(np.int64)
            fit_data = fit_data[fit_indices]

    prelabeler = RobustCFARPrelabeler(config).fit(fit_data)
    output_dir = output_root / _safe_directory_name(entry["name"])
    sample_dir = output_dir / "samples"
    sample_dir.mkdir(parents=True, exist_ok=True)
    prelabeler.save_calibration(output_dir / "normal_calibration.npz")
    np.save(output_dir / "fit_normal_indices.npy", fit_indices)

    pilot_indices = _select_pilot_indices(
        dataset["test_label"],
        normal_label=normal_label,
        pilot_label=pilot_label,
        pilot_count=pilot_count,
        seed=pilot_seed,
    )
    rows = []
    manifest_path = output_dir / "prelabels.jsonl"
    with manifest_path.open("w", encoding="utf-8", newline="\n") as handle:
        for test_index in pilot_indices:
            test_index_int = int(test_index)
            result = prelabeler.prelabel(dataset["test_data"][test_index_int])
            relative_artifact = Path("samples") / f"test_{test_index_int:05d}.npz"
            test_label = float(
                np.asarray(dataset["test_label"]).reshape(-1)[test_index_int]
            )
            result.save_npz(
                output_dir / relative_artifact,
                extra_arrays={
                    "test_index": np.asarray(test_index_int, dtype=np.int64),
                    "test_label": np.asarray(test_label, dtype=np.float32),
                },
                extra_metadata={
                    "dataset_name": entry["name"],
                    "source_pkl": str(pkl_path),
                },
            )
            row = {
                "dataset_name": entry["name"],
                "source_pkl": str(pkl_path),
                "test_index": test_index_int,
                "test_label": test_label,
                "artifact": relative_artifact.as_posix(),
                "bbox": result.bbox,
                "proposal_pixels": result.diagnostics["proposal_pixels"],
                "max_score": result.diagnostics["max_score"],
                "retained_component_count": result.diagnostics[
                    "retained_component_count"
                ],
            }
            rows.append(row)
            handle.write(json.dumps(row, sort_keys=True, allow_nan=False) + "\n")

    input_hash_after = _sha256(pkl_path)
    if input_hash_after != input_hash_before:
        raise RuntimeError(f"Input PKL changed while processing: {pkl_path}")
    summary = {
        "dataset_name": entry["name"],
        "source_pkl": str(pkl_path),
        "source_sha256_before": input_hash_before,
        "source_sha256_after": input_hash_after,
        "source_unchanged": True,
        "train_count": int(dataset["train_data"].shape[0]),
        "fit_normal_count": int(fit_indices.size),
        "test_count": int(dataset["test_data"].shape[0]),
        "pilot_label": pilot_label,
        "pilot_count": int(pilot_indices.size),
        "pilot_indices": pilot_indices.tolist(),
        "proposal_nonempty_count": int(
            sum(row["proposal_pixels"] > 0 for row in rows)
        ),
        "config": config.to_dict(),
        "fit_diagnostics": prelabeler.fit_diagnostics,
        "prelabel_manifest": str(manifest_path),
    }
    with (output_dir / "summary.json").open("w", encoding="utf-8") as handle:
        json.dump(summary, handle, indent=2, sort_keys=True, allow_nan=False)
    return summary


def main(argv: Sequence[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    config = config_from_args(args)
    output_root = args.output_dir.resolve()
    output_root.mkdir(parents=True, exist_ok=True)

    if args.pilot_manifest is not None:
        if args.dataset_pkl or args.manifest is not None:
            parser.error(
                "--pilot-manifest cannot be combined with --dataset-pkl or "
                "--manifest"
            )
        if (
            args.target_normal_proposal_rate is not None
            and not 0.0 < args.target_normal_proposal_rate < 1.0
        ):
            parser.error("--target-normal-proposal-rate must be in (0, 1)")
        run_manifest = process_pilot_manifest(
            args.pilot_manifest,
            output_root=output_root,
            config=config,
            normal_calibration_fraction=args.normal_calibration_fraction,
            normal_split_seed=args.normal_split_seed,
            fit_max_samples=args.fit_max_samples,
            target_normal_proposal_rate=args.target_normal_proposal_rate,
            threshold_search_min=args.threshold_search_min,
            threshold_search_max=args.threshold_search_max,
            threshold_search_step=args.threshold_search_step,
            strong_threshold_margin=args.strong_threshold_margin,
        )
        with (output_root / "run_manifest.json").open(
            "w",
            encoding="utf-8",
        ) as handle:
            json.dump(
                run_manifest,
                handle,
                indent=2,
                sort_keys=True,
                allow_nan=False,
            )
        print(json.dumps(run_manifest, indent=2, sort_keys=True, allow_nan=False))
        return 0

    if args.target_normal_proposal_rate is not None:
        parser.error(
            "--target-normal-proposal-rate requires --pilot-manifest"
        )
    entries = resolve_dataset_entries(args.dataset_pkl, args.manifest)
    summaries = []
    used_names: set[str] = set()
    for dataset_offset, entry in enumerate(entries):
        safe_name = _safe_directory_name(entry["name"])
        if safe_name in used_names:
            raise ValueError(f"Duplicate output dataset name: {safe_name}")
        used_names.add(safe_name)
        summaries.append(
            process_dataset(
                entry,
                output_root=output_root,
                config=config,
                normal_label=args.normal_label,
                pilot_label=args.pilot_label,
                pilot_count=args.pilot_count,
                pilot_seed=args.pilot_seed + dataset_offset,
                fit_max_samples=args.fit_max_samples,
            )
        )

    run_manifest = {
        "method": "normal_train_log_median_mad_plus_robust_local_cfar",
        "deep_model_used": False,
        "input_files_modified": False,
        "output_dir": str(output_root),
        "config": config.to_dict(),
        "datasets": summaries,
    }
    with (output_root / "run_manifest.json").open("w", encoding="utf-8") as handle:
        json.dump(
            run_manifest,
            handle,
            indent=2,
            sort_keys=True,
            allow_nan=False,
        )
    print(json.dumps(run_manifest, indent=2, sort_keys=True, allow_nan=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
